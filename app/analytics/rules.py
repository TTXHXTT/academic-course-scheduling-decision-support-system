"""
ACS Recommendation Rules Engine

Generates explainable course-offering recommendations based on course metrics.
All rules are transparent and documented. Thresholds are configurable.

SRS Reference: FR-05, FR-06, Module F

IMPORTANT: These are prototype assumption thresholds, not approved CSUSB policies.
All thresholds are shown to users alongside recommendations.
"""
from __future__ import annotations
from dataclasses import dataclass, field
from typing import List, Optional, Any

from .metrics import CourseMetrics


@dataclass
class RuleResult:
    """
    A single recommendation generated by a rule.
    Contains full evidence and explanation for user inspection (FR-06).
    """
    course_id: str
    course_name: Optional[str]
    category: str          # machine-readable category code
    category_label: str    # human-readable category
    priority: str          # high, medium, low, informational
    title: str
    explanation: str       # why this recommendation was generated
    rule_applied: str      # which rule code
    rule_description: str  # description of the rule
    limitations: str       # data limitations
    suggested_followup: str
    key_metric_name: Optional[str] = None
    key_metric_value: Optional[float] = None
    key_metric_threshold: Optional[float] = None
    insufficient_evidence: bool = False
    evidence_items: List[dict] = field(default_factory=list)  # supporting observations


class RecommendationRules:
    """
    Collection of all recommendation rules.
    Rules are applied independently; one course may have multiple recommendations.
    
    Threshold defaults are prototype assumptions documented in config.py.
    """

    RULE_DESCRIPTIONS = {
        "REC-001": "A course is recommended for an additional section when its average capacity utilization consistently exceeds the high-utilization threshold.",
        "REC-002": "A course shows an increasing enrollment trend based on linear regression of term-by-term average enrollments.",
        "REC-003": "A course reaches or nearly reaches full capacity in a significant proportion of its historical sections.",
        "REC-004": "A course shows consistently low capacity utilization, suggesting potential overcapacity or declining demand.",
        "REC-005": "A course has recorded unmet demand (students who tried to enroll but could not).",
        "REC-006": "A course has too few historical observations to support a reliable demand analysis.",
        "REC-007": "A course shows different utilization patterns across different modalities, warranting investigation.",
    }

    def __init__(self, parameters):
        self.params = parameters

    def evaluate(self, metrics: CourseMetrics) -> List[RuleResult]:
        """Apply all rules to a course's metrics. Returns list of recommendations."""
        results = []

        # REC-006: Insufficient data - check first, affects other rules
        if metrics.insufficient_data:
            results.append(self._rec_insufficient_data(metrics))
            return results  # No point applying other rules

        # REC-001: High utilization -> consider adding section
        rec = self._rec_high_utilization(metrics)
        if rec:
            results.append(rec)

        # REC-002: Increasing demand
        rec = self._rec_increasing_demand(metrics)
        if rec:
            results.append(rec)

        # REC-003: Frequently full
        rec = self._rec_frequently_full(metrics)
        if rec:
            results.append(rec)

        # REC-004: Low utilization
        rec = self._rec_low_utilization(metrics)
        if rec:
            results.append(rec)

        # REC-005: Unmet demand
        rec = self._rec_unmet_demand(metrics)
        if rec:
            results.append(rec)

        return results

    def _rec_high_utilization(self, m: CourseMetrics) -> Optional[RuleResult]:
        """REC-001: High average utilization suggests need for additional section."""
        if m.avg_utilization_pct is None:
            return None
        if m.avg_utilization_pct < self.params.high_utilization_threshold:
            return None

        evidence = [
            {"type": "avg_utilization", "metric": "avg_utilization_pct",
             "value": round(m.avg_utilization_pct, 1),
             "description": f"Average capacity utilization: {m.avg_utilization_pct:.1f}% across {m.valid_sections} section(s)"}
        ]
        for term, util in m.utilization_by_term.items():
            evidence.append({
                "type": "term_utilization", "term": term,
                "value": round(util, 1),
                "description": f"{term}: {util:.1f}% utilization"
            })

        return RuleResult(
            course_id=m.course_id,
            course_name=m.course_name,
            category="consider_adding_section",
            category_label="Consider Adding a Section",
            priority="high",
            title=f"High Capacity Utilization ({m.avg_utilization_pct:.1f}%)",
            explanation=(
                f"Course {m.course_id} has an average weighted capacity utilization of "
                f"{m.avg_utilization_pct:.1f}%, which exceeds the high-utilization threshold of "
                f"{self.params.high_utilization_threshold}%. This suggests the current number of "
                f"sections may be insufficient to meet student demand."
            ),
            rule_applied="REC-001",
            rule_description=self.RULE_DESCRIPTIONS["REC-001"],
            limitations=" ".join(m.limitations) if m.limitations else "None identified.",
            suggested_followup=(
                "Review enrollment trends for this course. If demand is confirmed, consider "
                "adding one or more sections in the next offering period. Verify instructor "
                "availability and room capacity before scheduling."
            ),
            key_metric_name="avg_utilization_pct",
            key_metric_value=m.avg_utilization_pct,
            key_metric_threshold=self.params.high_utilization_threshold,
            evidence_items=evidence,
        )

    def _rec_increasing_demand(self, m: CourseMetrics) -> Optional[RuleResult]:
        """REC-002: Increasing enrollment trend."""
        if m.demand_trend != "INCREASING":
            return None

        slope_str = f"+{m.demand_trend_score:.1f}" if m.demand_trend_score else "N/A"
        evidence = [
            {"type": "demand_trend", "metric": "demand_trend_score",
             "value": m.demand_trend_score,
             "description": f"Linear regression slope: {slope_str} students per term across {m.terms_offered} terms"},
            {"type": "terms_offered", "value": m.terms_offered,
             "description": f"Course offered in {m.terms_offered} terms: {', '.join(m.terms_list)}"},
        ]

        return RuleResult(
            course_id=m.course_id,
            course_name=m.course_name,
            category="investigate_increasing_demand",
            category_label="Investigate Increasing Demand",
            priority="medium",
            title=f"Increasing Enrollment Trend ({slope_str} students/term)",
            explanation=(
                f"Course {m.course_id} shows an increasing enrollment trend based on linear "
                f"regression of average enrollment per term (slope: {slope_str} students/term). "
                f"This trend was computed across {m.terms_offered} offered terms."
            ),
            rule_applied="REC-002",
            rule_description=self.RULE_DESCRIPTIONS["REC-002"],
            limitations=" ".join(m.limitations) if m.limitations else "None identified.",
            suggested_followup=(
                "Monitor enrollment in upcoming terms. If the upward trend continues, "
                "proactively plan for additional sections or increased capacity."
            ),
            key_metric_name="demand_trend_score",
            key_metric_value=m.demand_trend_score,
            key_metric_threshold=self.params.increasing_demand_slope,
            evidence_items=evidence,
        )

    def _rec_frequently_full(self, m: CourseMetrics) -> Optional[RuleResult]:
        """REC-003: Course frequently reaches capacity."""
        if m.full_capacity_rate is None:
            return None
        if m.full_capacity_rate < self.params.frequently_full_threshold:
            return None

        pct_str = f"{m.full_capacity_rate * 100:.0f}%"
        evidence = [
            {"type": "full_capacity_freq", "metric": "full_capacity_rate",
             "value": m.full_capacity_rate,
             "description": f"{pct_str} of sections reached ≥{self.params.full_capacity_threshold*100:.0f}% capacity ({m.full_capacity_count}/{m.valid_sections} sections)"},
        ]

        return RuleResult(
            course_id=m.course_id,
            course_name=m.course_name,
            category="investigate_repeatedly_full",
            category_label="Investigate Repeatedly Full Course",
            priority="high",
            title=f"Repeatedly Reaches Capacity ({pct_str} of sections)",
            explanation=(
                f"Course {m.course_id} reaches at least {self.params.full_capacity_threshold*100:.0f}% "
                f"capacity in {pct_str} of its historical sections ({m.full_capacity_count} of "
                f"{m.valid_sections}). This pattern suggests recurring high demand relative to "
                f"the number of seats offered."
            ),
            rule_applied="REC-003",
            rule_description=self.RULE_DESCRIPTIONS["REC-003"],
            limitations=" ".join(m.limitations) if m.limitations else "None identified.",
            suggested_followup=(
                "Investigate whether unmet demand exists for this course. Consider increasing "
                "section capacity or offering additional sections, pending instructor and room availability."
            ),
            key_metric_name="full_capacity_rate",
            key_metric_value=m.full_capacity_rate,
            key_metric_threshold=self.params.frequently_full_threshold,
            evidence_items=evidence,
        )

    def _rec_low_utilization(self, m: CourseMetrics) -> Optional[RuleResult]:
        """REC-004: Low utilization suggests overcapacity."""
        if m.avg_utilization_pct is None:
            return None
        # Only flag if we have enough data
        if m.valid_sections < 2:
            return None
        if m.avg_utilization_pct >= self.params.low_utilization_threshold:
            return None

        evidence = [
            {"type": "avg_utilization", "metric": "avg_utilization_pct",
             "value": round(m.avg_utilization_pct, 1),
             "description": f"Average capacity utilization: {m.avg_utilization_pct:.1f}%"},
        ]

        return RuleResult(
            course_id=m.course_id,
            course_name=m.course_name,
            category="review_low_utilization",
            category_label="Review Low Utilization Course",
            priority="low",
            title=f"Low Capacity Utilization ({m.avg_utilization_pct:.1f}%)",
            explanation=(
                f"Course {m.course_id} has an average weighted capacity utilization of only "
                f"{m.avg_utilization_pct:.1f}%, below the low-utilization threshold of "
                f"{self.params.low_utilization_threshold}%. This may indicate overcapacity, "
                f"declining demand, or a course that is offered more frequently than needed."
            ),
            rule_applied="REC-004",
            rule_description=self.RULE_DESCRIPTIONS["REC-004"],
            limitations=" ".join(m.limitations) if m.limitations else "None identified.",
            suggested_followup=(
                "Review whether the course is still in demand by checking student feedback "
                "and major requirements. Consider reducing section capacity or consolidating sections."
            ),
            key_metric_name="avg_utilization_pct",
            key_metric_value=m.avg_utilization_pct,
            key_metric_threshold=self.params.low_utilization_threshold,
            evidence_items=evidence,
        )

    def _rec_unmet_demand(self, m: CourseMetrics) -> Optional[RuleResult]:
        """REC-005: Documented unmet demand."""
        if not m.has_unmet_demand_data:
            return None
        if m.total_unmet_demand is None or m.total_unmet_demand <= 0:
            return None

        evidence = [
            {"type": "unmet_demand", "metric": "total_unmet_demand",
             "value": m.total_unmet_demand,
             "description": f"Total unmet demand: {m.total_unmet_demand} students across recorded terms"},
            {"type": "avg_unmet_demand", "metric": "avg_unmet_demand",
             "value": m.avg_unmet_demand,
             "description": f"Average unmet demand per section: {m.avg_unmet_demand:.1f} students"},
        ]

        return RuleResult(
            course_id=m.course_id,
            course_name=m.course_name,
            category="review_capacity_shortage",
            category_label="Review Potential Capacity Shortage",
            priority="high",
            title=f"Documented Unmet Demand ({m.total_unmet_demand} students)",
            explanation=(
                f"Course {m.course_id} has recorded unmet demand totaling {m.total_unmet_demand} "
                f"students (average {m.avg_unmet_demand:.1f} per section). This represents students "
                f"who attempted to enroll but could not due to capacity limits."
            ),
            rule_applied="REC-005",
            rule_description=self.RULE_DESCRIPTIONS["REC-005"],
            limitations=(
                "Unmet demand data is sourced directly from the imported dataset. "
                "This field is only populated when attempted_enrollment or unmet_demand "
                "data is present in the source data. These figures are not inferred."
            ),
            suggested_followup=(
                "Investigate the source of unmet demand. Consider adding sections, "
                "increasing capacity, or exploring alternative delivery modalities."
            ),
            key_metric_name="total_unmet_demand",
            key_metric_value=float(m.total_unmet_demand),
            key_metric_threshold=0.0,
            evidence_items=evidence,
        )

    def _rec_insufficient_data(self, m: CourseMetrics) -> RuleResult:
        """REC-006: Insufficient data for reliable analysis."""
        return RuleResult(
            course_id=m.course_id,
            course_name=m.course_name,
            category="review_insufficient_data",
            category_label="Review - Insufficient Historical Data",
            priority="informational",
            title="Insufficient Data for Reliable Analysis",
            explanation=(
                f"Course {m.course_id} has insufficient historical data to support "
                f"a reliable demand analysis. Only {m.total_sections} section(s) found."
            ),
            rule_applied="REC-006",
            rule_description=self.RULE_DESCRIPTIONS["REC-006"],
            limitations="; ".join(m.limitations),
            suggested_followup=(
                "Gather additional historical enrollment data for this course before "
                "drawing conclusions about its demand profile."
            ),
            insufficient_evidence=True,
            evidence_items=[
                {"type": "data_quality", "value": m.total_sections,
                 "description": f"Only {m.total_sections} section(s) found for this course"}
            ],
        )
